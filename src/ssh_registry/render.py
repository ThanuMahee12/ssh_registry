"""Generate the single ssh config file from the database."""

import sqlite3

HEADER = "# Generated by ssh-registry from the host database. Do not edit."


def _host_block(conn: sqlite3.Connection, host) -> list[str]:
    aliases = [r[0] for r in conn.execute(
        "SELECT pattern FROM host_name WHERE host_id = ? ORDER BY pattern", (host["id"],))]
    lines = [f"Host {' '.join([host['name'], *aliases])}"]
    if host["hostname"]:
        lines.append(f"  HostName {host['hostname']}")
    if host["login"]:
        lines.append(f"  User {host['login']}")
    if host["proxy"]:
        lines.append(f"  ProxyJump {host['proxy']}")
    if host["port"]:
        lines.append(f"  Port {host['port']}")
    if host["forward_agent"]:
        lines.append("  ForwardAgent yes")
    if host["identities_only"]:
        lines.append("  IdentitiesOnly yes")
    for (path,) in conn.execute("SELECT path FROM host_key WHERE host_id = ? ORDER BY seq", (host["id"],)):
        lines.append(f"  IdentityFile {path}")
    for key, value in conn.execute(
            "SELECT key, value FROM host_option WHERE host_id = ? ORDER BY key, seq", (host["id"],)):
        lines.append(f"  {key} {value}")
    return lines


def _account_blocks(conn: sqlite3.Connection, host) -> list[str]:
    out: list[str] = []
    for flag, user in conn.execute(
            """SELECT a.flag, l.user FROM account a JOIN login l ON l.id = a.login_id
               WHERE a.host_id = ? ORDER BY a.flag""", (host["id"],)):
        out += [
            f"Host {host['name']}_svc{flag}",
            "  RequestTTY yes",
            f"  RemoteCommand sudo su - {user}",
        ]
    return out


def render(conn: sqlite3.Connection) -> str:
    lines = [HEADER, ""]
    hosts = conn.execute(
        """SELECT h.id, h.name, h.hostname, h.port, h.forward_agent, h.identities_only,
                  l.user AS login, p.name AS proxy
           FROM host h
           LEFT JOIN login l ON l.id = h.login_id
           LEFT JOIN host p ON p.id = h.proxy_id
           ORDER BY h.sort_order, h.id""").fetchall()
    for host in hosts:
        lines += _host_block(conn, host)
        lines += _account_blocks(conn, host)
        lines.append("")
    return "\n".join(lines)
