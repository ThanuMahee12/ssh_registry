"""Generate the ssh config from the database.

Output is one file per usage (cw, personal, shared) plus shellrc.config, which
includes them in order. `shared` holds the Host * defaults and is included last,
so it stays last for ssh (first value wins, defaults come last).
"""

import sqlite3
from pathlib import Path

HEADER = "# Generated by ssh-registry from the host database. Do not edit."
USAGES = ["cw", "personal", "shared"]
INCLUDE_PREFIX = "~/.shellrc"


def _host_block(conn: sqlite3.Connection, host) -> list[str]:
    aliases = [r[0] for r in conn.execute(
        "SELECT pattern FROM host_name WHERE host_id = ? ORDER BY pattern", (host["id"],))]
    lines = [f"Host {' '.join([host['name'], *aliases])}"]
    if host["hostname"]:
        lines.append(f"  HostName {host['hostname']}")
    if host["login"]:
        lines.append(f"  User {host['login']}")
    if host["proxy"]:
        lines.append(f"  ProxyJump {host['proxy']}")
    if host["port"]:
        lines.append(f"  Port {host['port']}")
    if host["forward_agent"]:
        lines.append("  ForwardAgent yes")
    if host["identities_only"]:
        lines.append("  IdentitiesOnly yes")
    for (path,) in conn.execute("SELECT path FROM host_key WHERE host_id = ? ORDER BY seq", (host["id"],)):
        lines.append(f"  IdentityFile {path}")
    for key, value in conn.execute(
            "SELECT key, value FROM host_option WHERE host_id = ? ORDER BY key, seq", (host["id"],)):
        lines.append(f"  {key} {value}")
    return lines


def _account_blocks(conn: sqlite3.Connection, host) -> list[str]:
    out: list[str] = []
    for flag, user in conn.execute(
            """SELECT a.flag, l.user FROM account a JOIN login l ON l.id = a.login_id
               WHERE a.host_id = ? ORDER BY a.flag""", (host["id"],)):
        out += [
            f"Host {host['name']}_svc{flag}",
            "  RequestTTY yes",
            f"  RemoteCommand sudo su - {user}",
        ]
    return out


def render(conn: sqlite3.Connection, usage: str | None = None) -> str:
    """The config text for one usage, or for every host when usage is None."""
    if usage is not None and usage not in USAGES:
        raise ValueError(f"unknown usage {usage!r}; expected one of {USAGES}")
    where = "WHERE h.usage = ?" if usage else ""
    args = (usage,) if usage else ()
    lines = [HEADER, ""]
    hosts = conn.execute(
        f"""SELECT h.id, h.name, h.hostname, h.port, h.forward_agent, h.identities_only,
                   l.user AS login, p.name AS proxy
            FROM host h
            LEFT JOIN login l ON l.id = h.login_id
            LEFT JOIN host p ON p.id = h.proxy_id
            {where}
            ORDER BY h.sort_order, h.id""", args).fetchall()
    for host in hosts:
        lines += _host_block(conn, host)
        lines += _account_blocks(conn, host)
        lines.append("")
    return "\n".join(lines)


def shellrc_include(prefix: str = INCLUDE_PREFIX) -> str:
    """shellrc.config: includes the usage files in order. Add this to ~/.ssh/config."""
    lines = [HEADER, "# Include this from ~/.ssh/config."]
    lines += [f"Include {prefix}/{u}.config" for u in USAGES]
    return "\n".join(lines) + "\n"


def write_all(conn: sqlite3.Connection, directory: Path) -> list[Path]:
    """Write cw.config, personal.config, shared.config and shellrc.config into directory."""
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for usage in USAGES:
        path = directory / f"{usage}.config"
        path.write_text(render(conn, usage), encoding="utf-8", newline="\n")
        written.append(path)
    path = directory / "shellrc.config"
    path.write_text(shellrc_include(), encoding="utf-8", newline="\n")
    written.append(path)
    return written
