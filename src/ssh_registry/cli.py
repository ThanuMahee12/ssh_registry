"""ssh-registry: fetch host JSONL from S3 and generate this user's ssh config."""

from __future__ import annotations

import argparse
import dataclasses
import os
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from . import creds as creds_mod
from . import settings as settings_mod
from .hosts import Host, RegistryError, apply_logins, load_dir
from .render import render


def warn(msg: str) -> None:
    print(f"ssh-registry: {msg}", file=sys.stderr)


def sync(s: settings_mod.Settings) -> bool:
    """Mirror the S3 prefix into the cache. False (cache untouched) on failure."""
    if not shutil.which("aws"):
        warn("aws CLI not found; using the cached copy")
        return False
    s.cache_dir.mkdir(parents=True, exist_ok=True)
    # Download to a staging dir first so a failed or partial sync never
    # damages the last good copy.
    with tempfile.TemporaryDirectory(dir=s.cache_dir.parent, prefix=".ssh_registry-") as tmp:
        r = subprocess.run(
            ["aws", "s3", "sync", "--only-show-errors", "--region", s.region,
             "--exclude", "*", "--include", "*.jsonl", s.s3_uri, tmp],
            capture_output=True, text=True,
        )
        if r.returncode != 0:
            warn(f"could not read {s.s3_uri}: {r.stderr.strip() or r.returncode}; using the cached copy")
            return False
        if not any(Path(tmp).glob("*.jsonl")):
            warn(f"{s.s3_uri} has no *.jsonl files; keeping the cached copy")
            return False
        for old in s.cache_dir.glob("*.jsonl"):
            old.unlink()
        for new in Path(tmp).glob("*.jsonl"):
            shutil.copy2(new, s.cache_dir / new.name)
    return True


def _names(hosts: list[Host]) -> list[str]:
    return [n for h in hosts for n in [*h.names, *h.svc_hosts()]]


def ssh_check(config: Path, names: list[str]) -> list[str]:
    """Hosts that `ssh -G` (parse only, never connects) cannot resolve."""
    if not shutil.which("ssh"):
        warn("ssh not found; skipping the resolve check")
        return []
    bad = []
    for n in names:
        r = subprocess.run(["ssh", "-F", str(config), "-G", n], capture_output=True, text=True)
        if r.returncode != 0:
            bad.append(f"{n}: {r.stderr.strip()}")
    return bad


def write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def load_hosts(args, s: settings_mod.Settings) -> tuple[list[Host], str]:
    if args.src:
        src = Path(args.src)
        origin = str(src)
    else:
        if not args.offline:
            sync(s)
        src = s.cache_dir
        origin = f"{s.s3_uri} (cache {s.cache_dir})"
        if not any(src.glob("*.jsonl")):
            raise RegistryError(f"no host data: {s.s3_uri} unreachable and nothing cached in {s.cache_dir}")
    return load_dir(src), origin


def cmd_generate(args, s) -> int:
    hosts, origin = load_hosts(args, s)
    if args.user:  # one-off: as if cred.toml [global] user were this
        creds = {k: dict(v) for k, v in s.creds.items()}
        creds.setdefault(creds_mod.GLOBAL, {})["user"] = args.user
        s = dataclasses.replace(s, creds=creds)
    apply_logins(hosts, s)
    out = Path(args.out).expanduser() if args.out else s.output
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    header = (f"# GENERATED by ssh-registry at {stamp} from {origin}\n"
              "# Do not edit: change the JSONL (servers) or `shellrc config` (your login\n"
              "# and key), then re-run `shellrc generate`.")
    text = render(hosts, header, s.ssh_defaults)

    # Check the new file BEFORE it replaces the old one.
    with tempfile.NamedTemporaryFile("w", suffix=".config", delete=False) as f:
        f.write(text)
    try:
        bad = ssh_check(Path(f.name), _names(hosts))
    finally:
        os.unlink(f.name)
    if bad:
        warn("generated config does not resolve; " + str(out) + " left unchanged:\n  " + "\n  ".join(bad))
        return 1

    if args.stdout:
        sys.stdout.write(text)
        return 0
    write_atomic(out, text)
    print(f"wrote {out}: {len(hosts)} hosts from {origin}")
    if not _included(out):
        print(f"note: ~/.ssh/config does not Include it yet. Add as the FIRST line:\n  Include {out}")
    return 0


def _included(out: Path) -> bool:
    cfg = Path.home() / ".ssh" / "config"
    if not cfg.is_file():
        return False
    targets = {str(out), str(out).replace(str(Path.home()), "~", 1)}
    for line in cfg.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0].lower() == "include" and set(parts[1:]) & targets:
            return True
    return False


def cmd_check(args, s) -> int:
    hosts, origin = load_hosts(args, s)
    modules = len({h.module for h in hosts})
    print(f"ok: {modules} modules, {len(hosts)} servers, {len(_names(hosts))} host names from {origin}")
    return 0


def cmd_sync(args, s) -> int:
    ok = sync(s)
    if ok:
        print(f"synced {s.s3_uri} -> {s.cache_dir}")
    return 0 if ok else 1


def cmd_config(args, s) -> int:
    section = creds_mod.GLOBAL if args.glob else args.module
    if section is None and (args.user is not None or args.key is not None or args.unset):
        raise RegistryError("say where: --global (every host) or --module <name>")
    if section is None:  # show
        if not s.cred_file.is_file():
            print(f"{s.cred_file}: not set yet. Start with:\n  shellrc config --global --user your.login --key ~/.ssh/id_ed25519")
            return 0
        print(f"# {s.cred_file}")
        sys.stdout.write(creds_mod.dump(s.creds).split("\n", 2)[2])
        return 0
    if args.user is None and args.key is None and not args.unset:
        raise RegistryError("nothing to set: give --user, --key or --unset")
    if args.module:
        known = {p.stem for p in s.cache_dir.glob("*.jsonl")}
        if known and args.module not in known:
            warn(f"module '{args.module}' is not in the registry ({', '.join(sorted(known))}); saved anyway")
    if args.key is not None:
        note = creds_mod.check_key(args.key)
        if note:
            warn(note)
    creds_mod.set_values(s.cred_file, section, args.user, args.key, args.unset)
    print(f"saved [{section}] in {s.cred_file}. Run `shellrc generate` to apply it.")
    return 0


def cmd_list(args, s) -> int:
    hosts, _ = load_hosts(args, s)
    for h in hosts:
        print("\t".join([h.module, h.name, h.hostname, ",".join(h.aliases), h.proxy or "", ",".join(h.service_users)]))
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="ssh-registry", description=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)

    def common(sp):
        sp.add_argument("--src", help="read JSONL from this local directory instead of S3")
        sp.add_argument("--offline", action="store_true", help="use the cached copy, do not contact S3")

    g = sub.add_parser("generate", help="sync from S3 and write the ssh config")
    common(g)
    g.add_argument("--out", help="write here instead of settings [output] config")
    g.add_argument("--user", help="use this login for this run only (instead of cred.toml [global] user)")
    g.add_argument("--stdout", action="store_true", help="print the config instead of writing it")
    g.set_defaults(fn=cmd_generate)

    c = sub.add_parser("check", help="validate the JSONL without writing anything")
    common(c)
    c.set_defaults(fn=cmd_check)

    cf = sub.add_parser("config", help="set your login and key (~/.shellrc/cred.toml); no flags = show")
    where = cf.add_mutually_exclusive_group()
    where.add_argument("--global", dest="glob", action="store_true", help="for every host")
    where.add_argument("--module", help="for one module, e.g. cw_alchmy")
    cf.add_argument("--user", help="login name")
    cf.add_argument("--key", help="path to your private key file, e.g. ~/.ssh/id_ed25519")
    cf.add_argument("--unset", action="append", choices=["user", "key"], help="remove a value")
    cf.set_defaults(fn=cmd_config)

    sy = sub.add_parser("sync", help="only refresh the cache from S3")
    sy.set_defaults(fn=cmd_sync)

    ls = sub.add_parser("list", help="module, name, host, aliases, proxy, service flags (tab-separated)")
    common(ls)
    ls.set_defaults(fn=cmd_list)

    args = p.parse_args(argv)
    try:
        return args.fn(args, settings_mod.load())
    except (RegistryError, creds_mod.CredError) as e:
        warn(str(e))
        return 2


if __name__ == "__main__":
    sys.exit(main())
